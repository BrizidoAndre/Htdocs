    }




    public function validateMachine(){
        $errors  = [];

        if($this->processor && $this->motherboard->socketTypeId !== $this->processor->socketTypeId){
            $errors['Tipo do sockete'] = 'O tipo do soquete da placa-mãe é incompativel com o soquete do processador';
        }
        if($this->processor && $this->motherboard->maxTdp < $this->processor->tdp){
            $errors['TDP'] = 'O TDP do processador supera o permitido pela placa-mãe';
        }
        if($this->ramMemory && $this->motherboard->ramMemoryTypeId !== $this->ramMemory->ramMemoryTypeId){
            $errors['Tipo da memória RAM'] = 'O tipo da memória RAM é incompatível';
        }
        if($this->motherboard->ramMemorySlots < $this->ramMemoryAmount || $this->ramMemoryAmount < 1){
            $errors['Quantidade de memória RAM'] = 'A quantidade de memória RAM é incompatível com a placa-mãe';
        }
        if($this->motherboard->pciSlots< $this->graphicCardAmount || $this->graphicCardAmount < 1){
            $errors['Quantidade de placas de vídeo'] = 'A quantidade de placas de vídeo é incompatível com a placa-mãe';
        }
        if($this->graphicCard && $this->graphicCardAmount > 1 && !$this->graphicCard->supportMultiGpu){
            $errors['Quantidade de placas de vídeo'] = 'A placa de vídeo não suporta multiplataforma';
        }
        if($this->graphicCard && $this->powerSupply->potency < $this->graphicCard->minimumPowerSupply * $this->graphicCardAmount){
            $errors['Potência da fonte de alimentação'] = 'A fonte de alimentação não cobre o exigido mínimo da máquina';
        }

        $sataAmount = 0;
        $m2Amount = 0;
        foreach ($this->storageDevices as $item) {
            $storage = Storagedevice::findOne(['id' => $item['storageDeviceId']]);

            if(!$storage){
                $errors['inválido'] = 'O id fornecido está inválido';
                break;
            }

            if($storage->storageDeviceInterface === 'sata'){
                $sataAmount += $item['amount'];
            }
            if($storage->storageDeviceInterface === 'm2'){
                $m2Amount += $item['amount'];
            }
        }

        if($sataAmount + $m2Amount < 1){
            $errors['Armazenamento faltando'] = 'a máquina não possui armazenamento';
        }

        if($this->motherboard->sataSlots < $sataAmount){
            $errors['Quantidade SATA'] = 'A quantidade de dispositivos sata é maior que o suportado pela placa mãe';
        }
        if($this->motherboard->m2Slots < $m2Amount){
            $errors['Quantidade m2'] = 'A quantidade de dispositivos m2 é maior que o suportado pela placa mãe';
        }
        return $errors;

    }


    public function generateImage(){
        $base64 = explode(',', $this->imageBase64)[1];

        if(str_starts_with($base64,'/9j/')){
            $image = base64_decode($base64);

            $random = random_int(1, 999999);

            $jpgPath = Yii::getAlias('@webroot') . '/images/' . $random . '.jpg';

            file_put_contents($jpgPath, $image);

            $this->imageUrl = (string) $random;
        }
        else{
            $image = base64_decode($base64);

            $random = random_int(1, 999999);

            $jpgPath = Yii::getAlias('@webroot') . '/images/' . $random . '.png';

            file_put_contents($jpgPath, $image);

            $this->imageUrl = (string) $random;
        }
    }
