<?php

namespace app\models;

use Yii;

/**
 * This is the model class for table "review".
 *
 * @property int $id
 * @property int $userId
 * @property int $movieId
 * @property string|null $content
 * @property int|null $stars
 * @property string $createdAt
 *
 * @property Movie $movie
 * @property Reviewevaluation[] $reviewevaluations
 * @property User $user
 */
class Review extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'review';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['userId', 'movieId', 'stars', 'content'], 'required'],
            [['userId', 'movieId', 'stars'], 'integer'],
            [['content'], 'string'],
            [['createdAt'], 'safe'],
            [['movieId'], 'exist', 'skipOnError' => true, 'targetClass' => Movie::class, 'targetAttribute' => ['movieId' => 'id']],
            [['userId'], 'exist', 'skipOnError' => true, 'targetClass' => User::class, 'targetAttribute' => ['userId' => 'id']],
        ];
    }

    public function fields()
    {
        $fields =  parent::fields(); // TODO: Change the autogenerated stub

        $fields['username'] = function(){
            return User::findOne(['id' => $this->userId])->username;
        };

        $fields['score']= function(){
            $reviewsEvaluation = Reviewevaluation::findAll(['reviewId' => $this->id]);

            $score = 0;

            foreach ($reviewsEvaluation as $item) {
                if($item->positive){
                    $score ++;
                }
                else{
                    $score --;
                }
            }

            return $score;
        };

        return $fields;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'userId' => 'User ID',
            'movieId' => 'Movie ID',
            'content' => 'Content',
            'stars' => 'Stars',
            'createdAt' => 'Created At',
        ];
    }

    /**
     * Gets query for [[Movie]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getMovie()
    {
        return $this->hasOne(Movie::class, ['id' => 'movieId']);
    }

    /**
     * Gets query for [[Reviewevaluations]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getReviewevaluations()
    {
        return $this->hasMany(Reviewevaluation::class, ['reviewId' => 'id']);
    }

    /**
     * Gets query for [[User]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getUser()
    {
        return $this->hasOne(User::class, ['id' => 'userId']);
    }
}
