    public static function findIdentityByAccessToken($token, $type = null)
    {
        $accessToken = Accesstoken::findOne(['tokenString' => $token]);

        if ($accessToken) {

            $dateToken = date_create_from_format('Y-m-d H:i:s', $accessToken->creationDate);
            $dateNow = new \DateTime();
            $interval = date_diff($dateToken, $dateNow);

            $minutes = $interval->days * 24 * 60;
            $minutes += $interval->h * 60;
            $minutes += $interval->m;

            if ($minutes < 60) {
                return self::findOne(['id' => $accessToken->userId]);
            }

            $accessToken->delete();
        }

        return self::findOne(['id' => 'none']);
    }

